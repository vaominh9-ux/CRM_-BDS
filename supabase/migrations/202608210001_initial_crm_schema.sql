create or replace function public.has_permission(requested_page text, requested_action text)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select coalesce(r.is_super or case requested_action
    when 'v' then rp.can_view
    when 'a' then rp.can_add
    when 'e' then rp.can_edit
    when 'd' then rp.can_delete
    else false end, false)
  from public.profiles p
  join public.roles r on r.role_key = p.role_key
  left join public.role_permissions rp on rp.role_key = p.role_key and rp.page_key = requested_page
  where p.id = auth.uid() and p.status = 'Active'
$$;

create or replace view public.deal_financials
with (security_invoker = true)
as
select d.*,
       coalesce(sum(p.amount_vnd), 0)::bigint as paid_vnd,
       greatest(d.deal_amount_vnd - coalesce(sum(p.amount_vnd), 0), 0)::bigint as balance_vnd
from public.deals d
left join public.deal_payments p on p.deal_id = d.id
group by d.id;

create or replace function public.validate_deal_payment()
returns trigger
language plpgsql
set search_path = ''
as $$
declare
  deal_total bigint;
  deal_status text;
  already_paid bigint;
begin
  select d.deal_amount_vnd, d.status
  into deal_total, deal_status
  from public.deals d
  where d.id = new.deal_id and d.deleted_at is null
  for update;

  if not found then raise exception 'Deal not found'; end if;
  if deal_status = 'Cancelled' then raise exception 'Deal is cancelled'; end if;

  select coalesce(sum(p.amount_vnd), 0)::bigint
  into already_paid
  from public.deal_payments p
  where p.deal_id = new.deal_id and (tg_op = 'INSERT' or p.id <> new.id);

  if already_paid + new.amount_vnd > deal_total then
    raise exception 'Overpayment blocked. Remaining balance: %', deal_total - already_paid;
  end if;
  return new;
end;
$$;

create trigger deal_payments_validate
before insert or update on public.deal_payments
for each row execute function public.validate_deal_payment();

create or replace function public.record_deal_payment(
  target_deal_id bigint,
  payment_amount_vnd bigint,
  payment_method text default 'Cash',
  payment_reference text default '',
  payment_notes text default '',
  payment_time timestamptz default now()
)
returns public.deal_financials
language plpgsql
security invoker
set search_path = ''
as $$
declare
  locked_deal public.deals;
  already_paid bigint;
  result_row public.deal_financials;
begin
  if not public.has_permission('deals', 'e') then raise exception 'Access denied'; end if;
  if payment_amount_vnd <= 0 then raise exception 'Payment amount must be positive'; end if;
  if payment_method not in ('Cash','Bank Transfer','Cheque','Online') then raise exception 'Invalid payment method'; end if;

  select * into locked_deal from public.deals where id = target_deal_id and deleted_at is null for update;
  if not found then raise exception 'Deal not found'; end if;
  if locked_deal.status = 'Cancelled' then raise exception 'Deal is cancelled'; end if;
  if not public.is_manager_or_admin() and locked_deal.agent_id <> auth.uid() then raise exception 'Not your deal'; end if;

  select coalesce(sum(amount_vnd), 0)::bigint into already_paid from public.deal_payments where deal_id = target_deal_id;
  if already_paid + payment_amount_vnd > locked_deal.deal_amount_vnd then
    raise exception 'Overpayment blocked. Remaining balance: %', locked_deal.deal_amount_vnd - already_paid;
  end if;

  insert into public.deal_payments(deal_id, paid_at, amount_vnd, method, reference, notes, received_by)
  values (target_deal_id, payment_time, payment_amount_vnd, payment_method, payment_reference, payment_notes, auth.uid());

  select * into result_row from public.deal_financials where id = target_deal_id;
  return result_row;
end;
$$;

create or replace view public.tenancy_financials
with (security_invoker = true)
as
select t.*,
       coalesce(p.collected_vnd, 0)::bigint as collected_vnd,
       case when t.status = 'Active' then
         greatest(
           (((extract(year from current_date)::integer - extract(year from t.start_date)::integer) * 12
             + extract(month from current_date)::integer - extract(month from t.start_date)::integer
             + case when extract(day from current_date) >= t.rent_due_day then 1 else 0 end)
            * t.monthly_rent_vnd) - coalesce(p.collected_vnd, 0), 0
         )::bigint
       else 0::bigint end as arrears_vnd
from public.tenancies t
left join (
  select tenancy_id, sum(amount_vnd)::bigint as collected_vnd
  from public.rent_payments group by tenancy_id
) p on p.tenancy_id = t.id;

