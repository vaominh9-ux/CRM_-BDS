create or replace function public.protect_profile_privileges()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if auth.uid() is not null and public.current_role() <> 'Admin' then
    if new.id <> old.id
       or new.username <> old.username
       or new.email <> old.email
       or new.role_key <> old.role_key
       or new.status <> old.status
       or new.monthly_target_vnd <> old.monthly_target_vnd
       or new.created_at <> old.created_at
       or new.created_by is distinct from old.created_by then
      raise exception 'Only an administrator may change identity, role, status, or target';
    end if;
  end if;
  return new;
end;
$$;

